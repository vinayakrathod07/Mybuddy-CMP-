package com.academialife.app

import android.app.AlertDialog
import android.os.Bundle
import android.os.CountDownTimer
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.EditText
import android.widget.FrameLayout
import android.widget.ImageView
import android.widget.LinearLayout
import android.widget.TextView
import android.widget.Toast
import androidx.fragment.app.Fragment
import androidx.lifecycle.lifecycleScope
import androidx.recyclerview.widget.LinearLayoutManager
import androidx.recyclerview.widget.RecyclerView
import kotlinx.coroutines.launch
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

class StudyPlannerFragment : Fragment() {

    private lateinit var tvTimerMode: TextView
    private lateinit var tvTimerCountdown: TextView
    private lateinit var tvTimerCycles: TextView
    private lateinit var btnPlayPause: FrameLayout
    private lateinit var ivPlayPause: ImageView
    private lateinit var btnReset: FrameLayout
    private lateinit var btnModeToggle: FrameLayout

    private lateinit var btnAutoGenerate: TextView
    private lateinit var btnManualAdd: TextView
    private lateinit var rvSessions: RecyclerView
    private lateinit var layoutEmpty: LinearLayout

    private lateinit var adapter: StudySessionAdapter

    // Timer state
    private var countDownTimer: CountDownTimer? = null
    private var isTimerRunning: Boolean = false
    private var isFocusMode: Boolean = true // true: 25m focus, false: 5m break
    private var timeLeftInMillis: Long = 25 * 60 * 1000L
    private var completedCycles: Int = 0

    override fun onCreateView(
        inflater: LayoutInflater, container: ViewGroup?, savedInstanceState: Bundle?
    ): View? {
        val root = inflater.inflate(R.layout.fragment_study_planner, container, false)

        tvTimerMode = root.findViewById(R.id.tvTimerMode)
        tvTimerCountdown = root.findViewById(R.id.tvTimerCountdown)
        tvTimerCycles = root.findViewById(R.id.tvTimerCycles)
        btnPlayPause = root.findViewById(R.id.btnTimerPlayPause)
        ivPlayPause = root.findViewById(R.id.ivPlayPauseIcon)
        btnReset = root.findViewById(R.id.btnTimerReset)
        btnModeToggle = root.findViewById(R.id.btnTimerModeToggle)

        btnAutoGenerate = root.findViewById(R.id.btnAutoGeneratePlan)
        btnManualAdd = root.findViewById(R.id.btnManualAddSession)
        rvSessions = root.findViewById(R.id.rvStudySessions)
        layoutEmpty = root.findViewById(R.id.layoutEmptySessions)

        adapter = StudySessionAdapter(
            emptyList(),
            onToggleStatus = { session ->
                viewLifecycleOwner.lifecycleScope.launch {
                    val newStatus = if (session.status == "completed") "scheduled" else "completed"
                    FirebaseRepository.updateStudySessionStatus(session.id, newStatus)
                    loadSessions()
                }
            },
            onDeleteClick = { session ->
                AlertDialog.Builder(requireContext())
                    .setTitle("Delete Study Block")
                    .setMessage("Remove '${session.title}'?")
                    .setPositiveButton("Delete") { _, _ ->
                        viewLifecycleOwner.lifecycleScope.launch {
                            FirebaseRepository.deleteStudySession(session.id)
                            Toast.makeText(context, "Session removed", Toast.LENGTH_SHORT).show()
                            loadSessions()
                        }
                    }
                    .setNegativeButton("Cancel", null)
                    .show()
            }
        )

        rvSessions.layoutManager = LinearLayoutManager(context)
        rvSessions.adapter = adapter

        // Timer actions
        btnPlayPause.setOnClickListener {
            if (isTimerRunning) pauseTimer() else startTimer()
        }

        btnReset.setOnClickListener {
            resetTimer()
        }

        btnModeToggle.setOnClickListener {
            switchTimerMode()
        }

        // Actions
        btnAutoGenerate.setOnClickListener {
            showAutoGenerateDialog()
        }

        btnManualAdd.setOnClickListener {
            showManualAddDialog()
        }

        updateTimerDisplay()
        loadSessions()
        return root
    }

    private fun startTimer() {
        countDownTimer = object : CountDownTimer(timeLeftInMillis, 1000) {
            override fun onTick(millisUntilFinished: Long) {
                timeLeftInMillis = millisUntilFinished
                updateTimerDisplay()
            }

            override fun onFinish() {
                isTimerRunning = false
                ivPlayPause.setImageResource(R.drawable.ic_play)
                if (isFocusMode) {
                    completedCycles++
                    tvTimerCycles.text = "Cycle $completedCycles of 4 completed • Great job!"
                    Toast.makeText(context, "Focus session complete! Take a 5-minute break.", Toast.LENGTH_LONG).show()
                    isFocusMode = false
                    timeLeftInMillis = 5 * 60 * 1000L
                } else {
                    Toast.makeText(context, "Break over! Ready for next focus session?", Toast.LENGTH_LONG).show()
                    isFocusMode = true
                    timeLeftInMillis = 25 * 60 * 1000L
                }
                updateTimerDisplay()
            }
        }.start()

        isTimerRunning = true
        ivPlayPause.setImageResource(R.drawable.ic_pause)
    }

    private fun pauseTimer() {
        countDownTimer?.cancel()
        isTimerRunning = false
        ivPlayPause.setImageResource(R.drawable.ic_play)
    }

    private fun resetTimer() {
        pauseTimer()
        timeLeftInMillis = if (isFocusMode) 25 * 60 * 1000L else 5 * 60 * 1000L
        updateTimerDisplay()
    }

    private fun switchTimerMode() {
        pauseTimer()
        isFocusMode = !isFocusMode
        timeLeftInMillis = if (isFocusMode) 25 * 60 * 1000L else 5 * 60 * 1000L
        updateTimerDisplay()
    }

    private fun updateTimerDisplay() {
        val minutes = (timeLeftInMillis / 1000) / 60
        val seconds = (timeLeftInMillis / 1000) % 60
        tvTimerCountdown.text = String.format(Locale.getDefault(), "%02d:%02d", minutes, seconds)

        if (isFocusMode) {
            tvTimerMode.text = "FOCUS SESSION • 25 MIN"
        } else {
            tvTimerMode.text = "SHORT BREAK • 5 MIN"
        }
    }

    private fun loadSessions() {
        viewLifecycleOwner.lifecycleScope.launch {
            val list = FirebaseRepository.getStudySessions()
            adapter.updateList(list)
            layoutEmpty.visibility = if (list.isEmpty()) View.VISIBLE else View.GONE
        }
    }

    private fun showAutoGenerateDialog() {
        AlertDialog.Builder(requireContext())
            .setTitle("✨ Smart Study Plan Generator")
            .setMessage("AcademiaLife will analyze your upcoming examination deadlines and high priority tasks to schedule an optimized 7-day study plan.\n\nGenerate routine now?")
            .setPositiveButton("Generate") { _, _ ->
                viewLifecycleOwner.lifecycleScope.launch {
                    val generated = FirebaseRepository.autoGenerateStudyPlan(daysAhead = 7, dailyHours = 4.0)
                    Toast.makeText(context, "Generated ${generated.size} optimized study blocks!", Toast.LENGTH_SHORT).show()
                    loadSessions()
                }
            }
            .setNegativeButton("Cancel", null)
            .show()
    }

    private fun showManualAddDialog() {
        val view = layoutInflater.inflate(R.layout.dialog_add_study_session, null)
        val etTitle = view.findViewById<EditText>(R.id.etSessionTitle)
        val etSub = view.findViewById<EditText>(R.id.etSessionSubject)
        val etDate = view.findViewById<EditText>(R.id.etSessionDate)
        val etStart = view.findViewById<EditText>(R.id.etSessionStart)
        val etDur = view.findViewById<EditText>(R.id.etSessionDuration)

        val sdf = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
        etDate.setText(sdf.format(Date()))
        etStart.setText("18:00")
        etDur.setText("90")

        AlertDialog.Builder(requireContext())
            .setTitle("Add Custom Study Block")
            .setView(view)
            .setPositiveButton("Schedule") { _, _ ->
                val title = etTitle.text.toString().trim()
                val sub = etSub.text.toString().trim().ifEmpty { "General Study" }
                val date = etDate.text.toString().trim().ifEmpty { sdf.format(Date()) }
                val start = etStart.text.toString().trim().ifEmpty { "18:00" }
                val dur = etDur.text.toString().toIntOrNull() ?: 90

                if (title.isNotEmpty()) {
                    viewLifecycleOwner.lifecycleScope.launch {
                        val session = StudySession(
                            title = title,
                            subjectName = sub,
                            sessionDate = date,
                            startTime = start,
                            durationMinutes = dur,
                            status = "scheduled",
                            recommendationReason = "Self-scheduled study block"
                        )
                        FirebaseRepository.addStudySession(session)
                        Toast.makeText(context, "Study session scheduled", Toast.LENGTH_SHORT).show()
                        loadSessions()
                    }
                } else {
                    Toast.makeText(context, "Session title is required", Toast.LENGTH_SHORT).show()
                }
            }
            .setNegativeButton("Cancel", null)
            .show()
    }

    override fun onDestroyView() {
        super.onDestroyView()
        countDownTimer?.cancel()
    }
}

